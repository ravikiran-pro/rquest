/**
 * Rquest category taxonomy: the single source of truth for categories and sub-categories.
 *
 *   Category      8 universal, customer-facing groups ("what part of life does it serve").
 *                 Derived from UN COICOP 2018 (household consumption by purpose), cross-checked
 *                 against the Overture Maps places taxonomy and the ONDC retail domains.
 *   Sub-category  The kind of shop or service. Every sub-category has a listing form (built
 *                 from a template in services/formSchema.js plus its own extra fields), a
 *                 default listing type, search keywords, and links to the master catalog.
 *
 * Keys are permanent identifiers: rename `name` freely, never change a `key`. Sub-category keys
 * equal the catalog's shop-type keys (catalog/seeds/shop_types.csv), so catalog items tagged
 * with a shop type match their sub-category without a mapping.
 *
 * To add a sub-category: append it below, then run `npm run taxonomy:sync` (updates the
 * database) and `npm run taxonomy:export-catalog` (updates the catalog seed file).
 *
 * Placement rules for anything new:
 *   1. Ask what part of life it serves, not whether it is a product or a service.
 *   2. A repair or service goes with the thing it serves (phone repair → electronics).
 *   3. A rental goes with the thing being rented.
 *   4. If the customer is a business, it goes to Business & Professional.
 *   5. Still unclear: where a customer would look first. Keywords make it findable anywhere.
 *
 * Field reference for a sub-category:
 *   template      form template key (services/formSchema.js FORM_TEMPLATES)
 *   extra_fields  fields appended to the template's fields
 *   omit_fields   template field keys this sub-category does not use
 *   listing_type  product | food | service | rental (default for new listings)
 *   keywords      lower-case words that identify it (shop matching, search, suggestions)
 *   catalog_nodes catalog.taxonomy_nodes ids whose items (and their descendants) apply
 *   ondc          ONDC retail domain codes; osm OpenStreetMap tags (for map imports)
 *   aliases       older names, including the legacy US category list, that now mean this
 */

